export function getFinalRemarksForLevel(level?: string): HpcFinalRemarkItem[] {
  if (!level || level === "all") return HPC_FINAL_COMPREHENSIVE_REMARKS;
  const cleanLvl = level.toLowerCase();
  return HPC_FINAL_COMPREHENSIVE_REMARKS.filter((item) => {
    if (cleanLvl.includes("निर्झर") || cleanLvl.includes("प्रवाह") || cleanLvl === "beginner") {
      return item.level === "निर्झर";
    }
    if (cleanLvl.includes("पर्वत") || cleanLvl === "proficient") {
      return item.level === "पर्वत";
    }
    if (cleanLvl.includes("आकाश") || cleanLvl === "advanced") {
      return item.level === "आकाश";
    }
    return item.level.toLowerCase().includes(cleanLvl);
  });
}

