/**
 * निवडलेल्या जिल्ह्यानुसार त्या जिल्ह्याचे अधिकृत तालुके मिळवा
 */
export function getTalukasForDistrict(district: string): SmartOption[] {
  if (!district || !district.trim()) return [];
  const clean = district.trim();
  let key = clean;
  if (clean.includes("अहमदनगर") || clean.includes("अहिल्यानगर")) key = "अहमदनगर";
  else if (clean.includes("संभाजीनगर") || clean.includes("औरंगाबाद")) key = "छत्रपती संभाजीनगर";
  else if (clean.includes("धाराशीव") || clean.includes("उस्मानाबाद")) key = "धाराशीव";

  const list = TALUKAS_BY_DISTRICT[key] || [];
  return list.map((t) => ({ label: t, value: t }));
}

